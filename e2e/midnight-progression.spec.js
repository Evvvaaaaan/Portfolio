test('a purchased gun completes an armed contract and earns its reward', async ({ page }, info) => {
  await start(page); await deliver(page, 2); await travel(page, 0, -32)
  await page.keyboard.press('KeyE')
  await panel(page, 'Armory')
  await page.locator('[data-item="pistol"]').getByRole('button', { name: 'Buy', exact: true }).click()
  await panel(page, 'Contracts')
  await page.locator('.md-product').filter({ hasText: 'HARBOR CLEANUP' }).getByRole('button', { name: 'Accept job' }).click()
  await travel(page, -168, 106)
  await page.waitForTimeout(800) // Capture the encounter after the follow camera reaches the harbor.
  await page.keyboard.down('KeyF')
  await page.waitForFunction(() => window.__midnight.state().enemies.some((e) => e.health < 90))
  await expect(page.locator('.md-ammo strong')).not.toHaveText('12')
  await page.screenshot({ path: info.outputPath('harbor-combat.png') })
  await page.waitForFunction(() => window.__midnight.state().completed === 3)
  await page.keyboard.up('KeyF')
  expect(await page.evaluate(() => window.__midnight.state().cash)).toBe(3000)
  await expect(page.locator('.midnight')).toHaveAttribute('data-phase', 'playing')
})

test('mobile catalog scrolls, purchases and touch firing fit in a narrow viewport', async ({ browser }, info) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
  const page = await context.newPage()
  await start(page); await deliver(page); await travel(page, 0, -32)
  await page.getByRole('button', { name: 'Exit car', exact: true }).click()
  await panel(page, 'Armory')
  const dialog = await page.getByRole('dialog').boundingBox()
  expect(dialog.x).toBeGreaterThanOrEqual(0); expect(dialog.x + dialog.width).toBeLessThanOrEqual(390)
  await page.locator('[data-item="pistol"]').getByRole('button', { name: 'Buy', exact: true }).click()
  await page.locator('[data-item="shotgun"]').scrollIntoViewIfNeeded()
  await expect(page.locator('[data-item="shotgun"]')).toBeVisible()
  await page.screenshot({ path: info.outputPath('mobile-armory.png') })
  await close(page)
  const trigger = page.getByRole('button', { name: 'Fire weapon', exact: true })
  const bounds = await trigger.boundingBox()
  expect(bounds.width).toBeGreaterThanOrEqual(44); expect(bounds.height).toBeGreaterThanOrEqual(44)
  const cdp = await context.newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: bounds.x + bounds.width / 2, y: bounds.y + bounds.height / 2, id: 1 }] })
  await page.waitForFunction(() => window.__midnight.state().weapons.pistol.loaded < 12)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await page.screenshot({ path: info.outputPath('mobile-combat.png') })
  await context.close()
})

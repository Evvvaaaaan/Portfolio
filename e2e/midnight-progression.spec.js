import { test, expect } from '@playwright/test'

async function start(page) {
  await page.goto('/gallery/midnight-dispatch?debug', { waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: 'Start your shift', exact: true }).click()
  await expect(page.locator('.midnight')).toHaveAttribute('data-phase', 'playing')
}
async function travel(page, x, z) { await page.evaluate(([px, pz]) => window.__midnight.travel(px, pz), [x, z]) }
async function deliver(page, count = 1) {
  if (!(await page.evaluate(() => window.__midnight.state().driving))) await page.keyboard.press('KeyE')
  for (let i = 0; i < count; i++) {
    const before = await page.evaluate(() => { const s = window.__midnight.state(); return { completed: s.completed, target: s.mission.points[s.mission.stage] } })
    await travel(page, before.target.x, before.target.z)
    await page.waitForFunction((n) => window.__midnight.state().completed > n, before.completed)
  }
}
async function panel(page, name) {
  if (!(await page.getByRole('dialog').count())) await page.getByRole('button', { name: 'Open city network', exact: true }).click()
  await page.getByRole('button', { name, exact: true }).click()
}
async function close(page) { await page.getByRole('button', { name: 'Close city network', exact: true }).click() }

test('earned cash buys a usable weapon, reloads it, and survives a browser reload', async ({ page }, info) => {
  const errors = []; page.on('pageerror', (e) => errors.push(e.message))
  await start(page)
  await deliver(page)
  await travel(page, 0, -32)
  await page.keyboard.press('KeyE')
  await panel(page, 'Armory')
  await page.locator('[data-item="pistol"]').getByRole('button', { name: 'Buy', exact: true }).click()
  await expect(page.locator('.md-wallet strong')).toHaveText('$150')
  await expect(page.locator('[data-item="pistol"]')).toContainText('OWNED')
  await page.screenshot({ path: info.outputPath('armory-purchased.png') })
  await close(page)
  await page.keyboard.down('KeyF')
  await page.waitForFunction(() => window.__midnight.state().weapons.pistol.loaded < 12)
  await page.keyboard.up('KeyF')
  await page.keyboard.press('KeyR')
  await page.waitForFunction(() => window.__midnight.state().weapons.pistol.loaded === 12)
  const ammo = await page.evaluate(() => window.__midnight.state().weapons.pistol)
  expect(ammo.reserve).toBeLessThan(36)
  await page.keyboard.press('Escape')
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.locator('.md-save-note')).toContainText('$150')
  await page.getByRole('button', { name: 'Start your shift', exact: true }).click()
  const saved = await page.evaluate(() => window.__midnight.state())
  expect(saved.weapons.pistol).toEqual(ammo)
  expect(saved.cash).toBe(150)
  expect(saved.job).toBe(1)
  expect(errors).toEqual([])
})

test('three jobs fund a faster car that can be bought, driven and retained', async ({ page }, info) => {
  await start(page); await deliver(page, 3)
  expect(await page.evaluate(() => window.__midnight.state().phase)).toBe('playing')
  await travel(page, -8, 0)
  await panel(page, 'Garage')
  await page.locator('[data-item="runner"]').getByRole('button', { name: 'Buy', exact: true }).click()
  await expect(page.locator('.md-wallet strong')).toHaveText('$1,050')
  await page.screenshot({ path: info.outputPath('garage-purchased.png') })
  await close(page)
  expect(await page.evaluate(() => window.__midnight.state().car.model)).toBe('runner')
  await travel(page, 0, 168)
  await page.keyboard.down('KeyW')
  await page.waitForFunction(() => window.__midnight.state().car.speed > 34)
  await page.keyboard.up('KeyW')
  await page.keyboard.press('Escape')
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: 'Start your shift', exact: true }).click()
  expect(await page.evaluate(() => window.__midnight.state().car.model)).toBe('runner')
})

